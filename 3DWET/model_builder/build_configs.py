def build_gotm_fabm_yaml(config: LakeConfig, output_dir: str) -> str:
    """Generate gotm_fabm.yaml (GOTM-FABM driver options).

    Content is fixed for all lakes: enables FABM with freshwater impact,
    state repair, shade/albedo/surface-drag feedbacks and the standard
    numerics (ode_method=10, split_factor=1, w_adv_discr=6, cnpar=1.0).

    Parameters
    ----------
    config : LakeConfig
        Lake configuration (unused; signature kept for API consistency).
    output_dir : str
        Directory where gotm_fabm.yaml will be written (created if missing).

    Returns
    -------
    str
        Absolute path to the generated gotm_fabm.yaml file.
    """
    os.makedirs(output_dir, exist_ok=True)

    content = """fabm:
  use: true
  freshwater_impact: true
  repair_state: true
  feedbacks:
    shade: true
    albedo: true
    surface_drag: true
  numerics:
    ode_method: 10
    split_factor: 1
    w_adv_discr: 6
    cnpar: 1.0
"""

    file_path = os.path.join(output_dir, "gotm_fabm.yaml")
    with open(file_path, "w", encoding="utf-8") as f:
        f.write(content)
    return os.path.abspath(file_path)


def build_output_yaml(config: LakeConfig, output_dir: str) -> str:
    """Generate output.yaml (GETM output specification).

    Content is fixed for all lakes: daily output of all registered variables
    (time_unit=day, time_step=1, source=*).

    Parameters
    ----------
    config : LakeConfig
        Lake configuration (unused; signature kept for API consistency).
    output_dir : str
        Directory where output.yaml will be written (created if missing).

    Returns
    -------
    str
        Absolute path to the generated output.yaml file.
    """
    os.makedirs(output_dir, exist_ok=True)

    content = """output:
   time_unit: day
   time_step: 1
   sync_interval: 0
   variables:
      - source: *
"""

    file_path = os.path.join(output_dir, "output.yaml")
    with open(file_path, "w", encoding="utf-8") as f:
        f.write(content)
    return os.path.abspath(file_path)


def build_all_configs(config: LakeConfig, output_dir: str) -> List[str]:
    """Generate all 5 config files. Returns list of generated file paths.

    Writes getm.inp, getm_fabm.inp, gotmturb.nml, gotm_fabm.yaml and
    output.yaml into ``output_dir``. Only getm.inp depends on the lake
    parameters; the remaining four are fixed templates shared by all lakes.

    Parameters
    ----------
    config : LakeConfig
        Lake configuration carrying run/grid/time/depth parameters.
    output_dir : str
        Directory where the config files will be written (created if missing).

    Returns
    -------
    list of str
        Absolute paths of the five generated config files, in the order:
        getm.inp, getm_fabm.inp, gotmturb.nml, gotm_fabm.yaml, output.yaml.
    """
    return [
        build_getm_inp(config, output_dir),
        build_getm_fabm_inp(config, output_dir),
        build_gotmturb_nml(config, output_dir),
        build_gotm_fabm_yaml(config, output_dir),
        build_output_yaml(config, output_dir),
    ]
