const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const container={innerHTML:''};
const listeners={};
container.on=(event,listener)=>{listeners[event]=listener;};
const plots=[];
let payload={shape:[2,2,2],xc:[0,100],yc:[0,200],bottom:[[5,0],[10,-10]],sigma:[-0.75,-0.25],
    data:[[[1,999],[2,999]],[[3,999],[4,999]]],min:1,max:4,units:'mg/L',long_name:'test'};
const plotly={newPlot:async(el,traces,layout,config)=>{
    assert.equal(container.innerHTML,'','loading placeholder is removed before Plotly appends its graph');
    plots.push({traces,layout,config});
}};
const context=vm.createContext({console,URL,URLSearchParams,window:{Plotly:plotly},Plotly:plotly,
    document:{getElementById:()=>container},fetch:async()=>({json:async()=>payload})});
vm.runInContext(fs.readFileSync('3DWET/app/static/js/viz3d.js','utf8'),context);
(async()=>{
    await context.render3DWaterBody('test',0,{ve:20,level:1});
    assert.equal(plots.length,1);
    const p=plots[0],field=p.traces.find(trace=>trace.meta?.scientificField===true);
    assert.equal(p.traces[0].name,'水面','the default lake view starts with the water surface, not a bed fill');
    assert.equal(p.traces[0].i.length,4,'the water surface preserves only wet-cell triangles');
    assert.ok(!p.traces.some(t=>t.meta?.waterbodyFrame==='bed'),'the default view keeps the basin bed hidden');
    assert.ok(field.intensity.every(v=>v>=3&&v<=4),'display interpolation uses only wet scalar values');
    assert.ok(field.customdata.every(v=>v[6]===3||v[6]===4),'hover retains exact raw wet-cell values');
    assert.equal(p.layout.scene.zaxis.tickvals.at(-1),-200);
    assert.equal(p.layout.scene.zaxis.ticktext.at(-1),'10','vertical exaggeration never changes depth labels');
    assert.ok(p.traces[0].lighting.ambient>=0.5,'lake floor stays readable under restrained directional lighting');
    assert.equal(p.traces[0].showscale,false,'the uncolored water surface does not claim a depth legend');
    assert.equal(field.cmin,1,'the displayed scientific field keeps its own value range');
    assert.equal(field.cmax,4,'the displayed scientific field keeps its own value range');
    assert.ok(p.traces.some(t=>t.name==='等深线'),'lake view provides depth contours');
    assert.ok(!p.traces.some(t=>t.meta?.networkMode),'continuous display hides mesh network lines by default');
    assert.equal(p.config.scrollZoom,true,'wheel zoom remains available');
    assert.equal(p.layout.paper_bgcolor,'#f7fafb','exported PNG retains the readable light canvas without relying on CSS');
    await context.render3DCloud('test',0,22,{ve:1});
    assert.equal(plots[1].traces[0].x.length,4,'cloud excludes land');
    assert.equal(plots[1].traces[0].z[0],-3.75,'cloud uses sigma depth rather than layer index');
    await context.render3DSurface('test',0,22,{ve:1});
    assert.equal(plots.length,2,'a grid without a complete wet volume cell cannot claim a drawable isosurface');
    assert.ok(container.innerHTML.includes('未形成可绘制等值面'));
    const original=payload;
    payload={...payload,bottom:[[5,8],[10,12]],data:[[[1,2],[1,2]],[[3,4],[3,4]]]};
    await context.render3DSurface('test',0,22,{ve:1});
    assert.equal(plots[2].traces[0].type,'mesh3d');
    assert.ok(plots[2].traces.every(t=>t.i.length>0),'successful isosurfaces submit physical triangles');
    payload=original;
    await context.render3DWaterBody('test',0,{ve:1,overlay:false});
    assert.ok(plots.at(-1).layout.title.text.includes('湖盆地形'),'bathymetry-only view identifies its depth field rather than the unshown scientific variable');
    const before=plots.length;
    payload={...payload,data:[[[null,null],[null,null]],[[null,null],[null,null]]]};
    await context.render3DWaterBody('test',0,{level:1});
    assert.equal(plots.length,before+1,'missing wet samples retain their physically located material');
    assert.ok(plots.at(-1).traces.some(t=>t.meta?.missingWater));
    assert.ok(plots.at(-1).traces.every(t=>!t.showscale&&!t.marker?.showscale),'missing material cannot claim a numeric scale');
    payload={depth:[[5,0],[10,-10]],nx:2,ny:2,xc:[0,100],yc:[0,200]};
    await context.renderBathymetry3D({ve:1});
    assert.equal(plots.at(-1).traces[0].i.length,4,'bathymetry preview needs no model output');
    container._fullLayout={scene:{camera:{eye:{x:2,y:1,z:0.5},center:{x:0,y:0,z:0},up:{x:0,y:0,z:1}}}};
    await context.renderBathymetry3D({ve:2});
    assert.equal(plots.at(-1).layout.scene.camera.eye.x,2,'refresh preserves the user camera');
    assert.equal(typeof listeners.plotly_relayout,'function','interactive camera changes are captured through the Plotly public event');
    listeners.plotly_relayout({'scene.camera':{eye:{x:3,y:2,z:1},center:{x:0,y:0,z:0},up:{x:0,y:0,z:1}}});
    await context.renderBathymetry3D({ve:1});
    assert.equal(plots.at(-1).layout.scene.camera.eye.x,3,'orbit and wheel-zoom camera overrides stale layout defaults');
    container._fullLayout.scene._scene={getCamera:()=>({eye:{x:4,y:2,z:1},center:{x:0,y:0,z:0},up:{x:0,y:0,z:1}})};
    await context.renderBathymetry3D({ve:1});
    assert.equal(plots.at(-1).layout.scene.camera.eye.x,4,'live WebGL camera wins when wheel event reports a stale layout camera');
    console.log('lake render: masks, true depth labels, volume arrays, empty data and preview PASS');
})().catch(e=>{console.error(e);process.exitCode=1;});
