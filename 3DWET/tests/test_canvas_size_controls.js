const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('3DWET/app/static/js/view_controls.js','utf8');
const host={style:{},classList:{add(){}},append(){},get clientWidth(){return Math.min(1000,parseFloat(this.style.width)||1000);},get clientHeight(){return parseFloat(this.style.height)||0;}};
const fields={'viz2d-width':{value:''},'viz2d-height':{value:'500'}};
const canvas={id:'viz2d-canvas',dataset:{},classList:{contains:()=>true},style:{},width:800,height:500,before(){},addEventListener(){}};
let hooks;
const context=vm.createContext({console,window:{innerHeight:720},document:{createElement:()=>host,getElementById:id=>fields[id]},registered:new Map(),registerGraphic:(c,h)=>{hooks=h;},resizeAll(){}});
vm.runInContext(source.slice(0,source.indexOf('(() =>')),context);
vm.runInContext(source.slice(source.indexOf('    function genericCanvas('),source.indexOf('    function installLibraries(')),context);
context.canvas=canvas;vm.runInContext('genericCanvas(canvas)',context);
assert.equal(Number(fields['viz2d-height'].value),396,'initial height control must match the dynamic viewport');
hooks.setSize(760,330);
assert.equal(host.style.width,'760px');assert.equal(Number(fields['viz2d-width'].value),760);
assert.equal(host.style.height,'330px');assert.equal(Number(fields['viz2d-height'].value),330);
assert.equal(canvas.style.width,'528px');assert.equal(canvas.style.height,'330px');
host.style.width='620px';host.style.height='410px';hooks.resize();
assert.equal(Number(fields['viz2d-width'].value),620,'native resize must update the width control');
assert.equal(Number(fields['viz2d-height'].value),410,'native resize must update the height control');
hooks.setSize(null,396);assert.equal(fields['viz2d-width'].value,'','fit restores automatic width');
assert.equal(Number(fields['viz2d-height'].value),396);
hooks.setSize(9000,9000);assert.equal(host.style.width,'4000px');assert.equal(host.style.height,'1600px');
context.getComputedStyle=()=>({paddingLeft:'12px',paddingRight:'12px',paddingTop:'12px',paddingBottom:'12px'});
hooks.setSize(600,300);
assert.equal(parseFloat(canvas.style.height),276,'fullscreen padding is outside the fitted graph');
assert.ok(parseFloat(canvas.style.width)<=576,'fitted graph must stay inside the padded host');
let scientificSize;
canvas._scientificResize=(w,h)=>{scientificSize=[w,h];};
hooks.setSize(600,300);
assert.deepEqual(scientificSize,[576,276],'scientific renderer receives the usable viewport for fresh readable geometry');
console.log('2D size controls: initial, numeric, native resize, fit and bounds PASS');
