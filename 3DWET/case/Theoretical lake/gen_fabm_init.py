"""Regenerate fabm_init.nc for the 24x20 Theoretical Lake grid.

The original fabm_init.nc was created with wrong dimension names (lon/lat
instead of x/y) and no FABM state variables, causing GETM to crash with
"FATAL ERROR: we assume to read from a 4D field - and ndims = 3".

This script creates a proper fabm_init.nc modelled on the working Lake Luoma
version: dimensions (x, y, time), coordinate vars (x, y, lonc, latc, time),
and macrophytes state variables (sD, sN, sP, sC) as 3D (time, y, x) fields.
"""
import netCDF4 as nc
import numpy as np
import os

CASE_DIR = os.path.dirname(os.path.abspath(__file__))
LUOMAHU_INIT = os.path.join(os.path.dirname(CASE_DIR), 'Lake Luoma', 'fabm_init.nc')
BATHY_PATH = os.path.join(CASE_DIR, 'bathymetry.nc')
OUT_PATH = os.path.join(CASE_DIR, 'fabm_init.nc')

# Read grid info from bathymetry.nc (authoritative source)
bds = nc.Dataset(BATHY_PATH)
NX = len(bds.dimensions['x'])
NY = len(bds.dimensions['y'])
x_1d = bds.variables['x'][:]
y_1d = bds.variables['y'][:]
lonc = bds.variables['lonc'][:]
latc = bds.variables['latc'][:]
bathy = np.ma.filled(bds.variables['bathymetry'][:], 0.0)
bds.close()

print(f'Grid: {NX} x {NY}')

# Read state variables and initial values from Lake Luoma fabm_init.nc
src = nc.Dataset(LUOMAHU_INIT)
src_dims = {k: len(v) for k, v in src.dimensions.items()}
src_vars = {}
for name, var in src.variables.items():
    src_vars[name] = {
        'dims': var.dimensions,
        'dtype': var.dtype,
        'attrs': {k: var.getncattr(k) for k in var.ncattrs()},
        'data': var[:],
    }
src.close()

print(f'Source variables: {list(src_vars.keys())}')

# Create new fabm_init.nc
ds = nc.Dataset(OUT_PATH, 'w', format='NETCDF4')
ds.createDimension('x', NX)
ds.createDimension('y', NY)
ds.createDimension('time', 1)

for name, info in src_vars.items():
    dims = info['dims']
    dtype = info['dtype']
    attrs = info['attrs']
    data = info['data']

    # Map source dimensions to new grid
    if dims == ('x',):
        new_var = ds.createVariable(name, dtype, ('x',))
        new_var.setncatts(attrs)
        new_var[:] = x_1d
    elif dims == ('y',):
        new_var = ds.createVariable(name, dtype, ('y',))
        new_var.setncatts(attrs)
        new_var[:] = y_1d
    elif dims == ('time',):
        new_var = ds.createVariable(name, dtype, ('time',))
        new_var.setncatts(attrs)
        new_var[:] = np.array([0.0])
    elif dims == ('y', 'x'):
        new_var = ds.createVariable(name, dtype, ('y', 'x'))
        new_var.setncatts(attrs)
        if name in ('lonc',):
            new_var[:] = lonc
        elif name in ('latc',):
            new_var[:] = latc
        else:
            fill = float(np.nanmean(data)) if data.size else 0.0
            new_var[:] = np.full((NY, NX), fill)
    elif dims == ('time', 'y', 'x'):
        new_var = ds.createVariable(name, dtype, ('time', 'y', 'x'))
        new_var.setncatts(attrs)
        fill = float(np.nanmean(data)) if data.size else 0.0
        new_var[:] = np.full((1, NY, NX), fill)
    else:
        print(f'  Skipping {name}: unhandled dims {dims}')

ds.title = 'Theoretical Lake FABM initial conditions (24x20 grid)'
ds.source = 'Generated by gen_fabm_init.py from Lake Luoma template'
ds.close()

print(f'Written: {OUT_PATH}')

# Verify
chk = nc.Dataset(OUT_PATH)
print(f'\nVerification:')
print(f'  Dimensions: {dict((k, len(v)) for k, v in chk.dimensions.items())}')
print(f'  Variables: {list(chk.variables.keys())}')
for name, var in chk.variables.items():
    print(f'    {name}: dims={var.dimensions}, shape={var.shape}')
chk.close()
